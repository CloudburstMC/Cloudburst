package org.cloudburstmc.api.boss;

/**
 * Visual divisions applied to a boss bar.
 */
public enum BossBarStyle {
    /**
     * A continuous bar.
     */
    SOLID,
    /**
     * A bar divided into six segments.
     */
    SEGMENTED_6,
    /**
     * A bar divided into ten segments.
     */
    SEGMENTED_10,
    /**
     * A bar divided into twelve segments.
     */
    SEGMENTED_12,
    /**
     * A bar divided into twenty segments.
     */
    SEGMENTED_20
}

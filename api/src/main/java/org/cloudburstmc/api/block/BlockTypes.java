    private static BlockType type(String id) {
        Identifier identifier = Identifier.parse(id);
        BlockType type = BlockRegistry.get().get(identifier)
                .orElseThrow(() -> new IllegalStateException("Missing built-in block type: " + identifier));
        return TYPES.register(type);
    }

    private static void type(Map<Identifier, BlockType> types, String id, BlockTrait<?>... traits) {
        BlockType type = new CloudBlockType(Identifier.parse(id), traits);
        if (types.putIfAbsent(type.getId(), type) != null) {
            throw new IllegalStateException("Duplicate built-in block type: " + type.getId());
        }
    }

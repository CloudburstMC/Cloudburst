    public static void register(CloudItemRegistry registry) {
        validate();

        for (Binding binding : BINDINGS) {
            registry.registerBlockItem(binding.item(), binding.placement(), binding.forms());
        }
    }

    private static void validate() {
        Set<BlockType> classifiedBlocks = new HashSet<>();
        Set<ItemType> boundItems = new HashSet<>();
        for (Binding binding : BINDINGS) {
            if (!boundItems.add(binding.item())) {
                throw new RegistryException("Duplicate block item binding for " + binding.item().getId());
            }

            classify(binding.placement(), classifiedBlocks);
            for (BlockType form : binding.forms()) {
                classify(form, classifiedBlocks);
            }
        }

        for (BlockType block : UNBOUND) {
            classify(block, classifiedBlocks);
        }

        List<Identifier> missing = BlockTypes.values().stream()
                .filter(block -> !classifiedBlocks.contains(block))
                .map(BlockType::getId)
                .toList();
        if (!missing.isEmpty()) {
            throw new RegistryException("Missing block item classification for " + missing);
        }
    }

    private static void classify(BlockType block, Set<BlockType> classified) {
        if (!classified.add(block)) {
            throw new RegistryException("Duplicate block item classification for " + block.getId());
        }
    }

    private static Binding binding(ItemType item, BlockType placement, BlockType... forms) {
        return new Binding(item, placement, List.of(forms));
    }

